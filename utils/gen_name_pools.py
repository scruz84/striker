#!/usr/bin/env python3
"""Generate the per-country name-pool migrations from their text sources.

Reads utils/namepools/<code>/first.txt and last.txt (one name per line, UTF-8, Latin script) and
writes backend/resources/sql/namepools/init91_name_pool_<code>.sql for each country, in the format
described in openspec/changes/add-all-fifa-countries/design.md (D2, now openspec/specs/country-catalog):

  * the INSERTs only run while name_pool_versions has no row for the country at the current
    POOL_VERSION or above, so re-applying the file on every startup is a cheap no-op;
  * a per-row NOT EXISTS keeps any names the table already had, so an old 30-name pool grows
    instead of being replaced;
  * the version row is written last.

A later enlargement of the pools bumps POOL_VERSION and regenerates.

Validation (the script exits non-zero and writes nothing if any country fails):
  * only Latin letters (diacritics allowed), space, ' - and . ;
  * at most MAX_LEN characters per name;
  * no duplicates, compared case-insensitively;
  * at least MIN_FIRST first names and MIN_LAST surnames.

Usage:
  python3 utils/gen_name_pools.py            # validate and write every country
  python3 utils/gen_name_pools.py --check    # validate only; also fails if a generated file is stale
  python3 utils/gen_name_pools.py fj jm      # only these countries
"""
import argparse
import sys
import unicodedata
from pathlib import Path

POOL_VERSION = 2
MIN_FIRST = 300
MIN_LAST = 500
MAX_LEN = 40
ALLOWED_PUNCT = set(" '-.")

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / "namepools"
OUT = ROOT.parent / "backend" / "resources" / "sql" / "namepools"


def is_latin(name: str) -> bool:
    for ch in name:
        if ch in ALLOWED_PUNCT:
            continue
        if not ch.isalpha():
            return False
        # unicodedata.name starts with e.g. "LATIN SMALL LETTER A WITH ACUTE"
        if not unicodedata.name(ch, "").startswith("LATIN"):
            return False
    return True


def dupe_key(name: str) -> str:
    """Case-insensitive identity of a name. The dotted capital I is folded to a plain i the way Go's
    strings.ToLower does (Python's casefold would make it i + combining dot), so this script and
    TestNamePoolFiles agree on what counts as a duplicate."""
    return name.replace("\u0130", "i").casefold()


def read_names(path: Path, minimum: int, errors: list) -> list:
    if not path.exists():
        errors.append(f"{path}: missing")
        return []
    seen = {}
    names = []
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        name = " ".join(raw.split())
        if not name:
            continue
        if len(name) > MAX_LEN:
            errors.append(f"{path}:{lineno}: {name!r} is longer than {MAX_LEN} characters")
            continue
        if not is_latin(name):
            errors.append(f"{path}:{lineno}: {name!r} is not Latin script")
            continue
        if not name[0].isalpha():
            errors.append(f"{path}:{lineno}: {name!r} must start with a letter")
            continue
        key = dupe_key(name)
        if key in seen:
            errors.append(f"{path}:{lineno}: {name!r} duplicates line {seen[key]}")
            continue
        seen[key] = lineno
        names.append(name)
    if len(names) < minimum:
        errors.append(f"{path}: {len(names)} distinct names, need at least {minimum}")
    return names


def sql_literal(name: str) -> str:
    return "'" + name.replace("'", "''") + "'"


def insert_block(table: str, column: str, code: str, names: list) -> str:
    values = ",".join("(" + sql_literal(n) + ")" for n in names)
    return (
        f'INSERT INTO {table} ({column}, freq)\n'
        f"SELECT v.n, 1.0 FROM (VALUES {values}) AS v(n)\n"
        f"WHERE NOT EXISTS (SELECT 1 FROM name_pool_versions WHERE country = '{code}' AND version >= {POOL_VERSION})\n"
        f'  AND NOT EXISTS (SELECT 1 FROM {table} e WHERE e.{column} = v.n);\n'
    )


def render(code: str, first: list, last: list) -> str:
    return (
        f"-- GENERATED by utils/gen_name_pools.py from utils/namepools/{code}/{{first,last}}.txt - do not edit.\n"
        f"-- Name pool of {code}: {len(first)} first names, {len(last)} surnames (pool version {POOL_VERSION}).\n"
        f"-- Skipped once name_pool_versions records this version; names the table already had are kept.\n"
        + insert_block(f"names_{code}", '"name"', code, first)
        + insert_block(f"lastnames_{code}", "lastname", code, last)
        + f"INSERT INTO name_pool_versions (country, version) VALUES ('{code}', {POOL_VERSION})\n"
        f"ON CONFLICT (country) DO UPDATE SET version = GREATEST(name_pool_versions.version, {POOL_VERSION});\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("codes", nargs="*", help="country codes to process (default: every directory in utils/namepools)")
    parser.add_argument("--check", action="store_true", help="validate only; fail if a generated file is missing or stale")
    args = parser.parse_args()

    codes = args.codes or sorted(p.name for p in SOURCES.iterdir() if p.is_dir())
    errors: list = []
    rendered = {}
    for code in codes:
        directory = SOURCES / code
        first = read_names(directory / "first.txt", MIN_FIRST, errors)
        last = read_names(directory / "last.txt", MIN_LAST, errors)
        if first and last:
            rendered[code] = render(code, first, last)

    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"{len(errors)} problem(s); nothing written", file=sys.stderr)
        return 1

    stale = []
    for code, text in rendered.items():
        target = OUT / f"init91_name_pool_{code}.sql"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target))
            continue
        OUT.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    if stale:
        print("stale or missing generated files (run utils/gen_name_pools.py):\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(rendered)} name pool(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
