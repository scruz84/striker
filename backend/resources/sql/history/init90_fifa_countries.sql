-- Adds the 148 FIFA member associations the game did not know yet (see common.KnownCountries and
-- the country-catalog OpenSpec spec), so every one of the 211 members can be activated by an admin.
-- Each new country needs its own names_<code>/lastnames_<code> pair (see common.GetRandomName); the
-- rows themselves are loaded by the generated per-country files in resources/sql/namepools/
-- (init91_name_pool_<code>.sql, produced by utils/gen_name_pools.py from utils/namepools/), which
-- sort after this file.
--
-- name_pool_versions records, per country, which generation of its name pool has been loaded. A
-- pool file only inserts when its version is not recorded yet, so after the first start every
-- re-application on startup is a cheap no-op, and a later enlargement of the pools only has to
-- bump the version in the generator.

CREATE TABLE IF NOT EXISTS name_pool_versions (
    country varchar(8) PRIMARY KEY,
    version int NOT NULL
);

